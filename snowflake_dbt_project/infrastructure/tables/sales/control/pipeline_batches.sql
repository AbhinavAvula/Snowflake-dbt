CREATE TABLE IF NOT EXISTS SALES_DB.CONTROL_SCM.PIPELINE_BATCHES (

    BATCH_ID VARCHAR(100) NOT NULL,
    DAG_ID VARCHAR(100),
    AIRFLOW_RUN_ID VARCHAR(255),
    BUSINESS_DATE DATE,

    STATUS VARCHAR(30) DEFAULT 'REGISTERED',

    EXPECTED_FILE_COUNT NUMBER,
    DISCOVERED_FILE_COUNT NUMBER,

    INGESTED_ROW_COUNT NUMBER DEFAULT 0,
    VALID_ROW_COUNT NUMBER DEFAULT 0,
    INVALID_ROW_COUNT NUMBER DEFAULT 0,
    GOLD_ROW_COUNT NUMBER DEFAULT 0,

    STARTED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    COMPLETED_AT TIMESTAMP_LTZ,

    ERROR_MESSAGE VARCHAR,

    CONSTRAINT PK_PIPELINE_BATCHES PRIMARY KEY (BATCH_ID)
);
