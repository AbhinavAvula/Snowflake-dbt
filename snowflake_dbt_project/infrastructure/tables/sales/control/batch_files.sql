CREATE TABLE IF NOT EXISTS SALES_DB.CONTROL_SCM.BATCH_FILES (

    BATCH_ID VARCHAR(100) NOT NULL,

    SOURCE_FILE VARCHAR(1000) NOT NULL,
    SOURCE_ETAG VARCHAR(255),
    SOURCE_VERSION_ID VARCHAR(255),
    FILE_SIZE_BYTES NUMBER,

    STATUS VARCHAR(30) DEFAULT 'DISCOVERED',

    ROWS_LOADED NUMBER DEFAULT 0,

    DISCOVERED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
    LOADED_AT TIMESTAMP_LTZ,

    ERROR_MESSAGE VARCHAR,

    CONSTRAINT PK_BATCH_FILES
        PRIMARY KEY (BATCH_ID, SOURCE_FILE)
);
